"""Writes results/e6/summary.md: report-ready tables generated from the E6 CSVs (no hand-copied numbers)."""

from __future__ import annotations

from pathlib import Path

import pandas as pd


def pct(x, digits: int = 1) -> str:
    return "–" if x is None or pd.isna(x) else f"{100 * float(x):.{digits}f}%"


def f4(x) -> str:
    return "–" if x is None or pd.isna(x) else f"{float(x):.4f}"


def ci(lo, hi, fmt=pct) -> str:
    return "" if lo is None or pd.isna(lo) else f" [{fmt(lo)}, {fmt(hi)}]"


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def write_summary(path: Path, thresholds, metrics, notinject, d3_slices, order, models) -> None:
    name = dict(zip(thresholds.model_id, thresholds.display_name)).get
    main = [m for m in order if models[m]["experiment"] in ("e1", "e2", "e3", "e4")]
    supp = [m for m in order if m not in main]
    parts = ["# E6 summary — operating thresholds and false alarms", "",
             "Generated by `experiments/e6/run_e6.py`; every number comes from `results/e6/*.csv`.",
             "Thresholds were selected on D1 Validation only and frozen before D1/D2/D3 Test and D4 were evaluated.",
             "Scores are uncalibrated. Main pipelines are E1–E4; E5 rows are supplementary.", ""]

    # 1. thresholds
    rows = []
    for m in order:
        t = thresholds[thresholds.model_id == m].set_index("threshold_policy")
        rows.append([name(m), f4(t.loc["tF1", "threshold"]), f4(t.loc["tF1", "val_macro_f1"]),
                     str(int(t.loc["tF1", "n_tied_candidates"])),
                     f4(t.loc["t5", "threshold"]), pct(t.loc["t5", "val_attack_recall"]), pct(t.loc["t5", "val_fpr"]),
                     f4(t.loc["default_0.5", "val_macro_f1"])])
    parts += ["## 1. Selected thresholds (D1 Validation, n = 1,985)", "",
              table(["Model", "tF1", "Val Macro F1 @tF1", "tied candidates", "t5", "Val recall @t5", "Val FPR @t5",
                     "Val Macro F1 @0.5"], rows), ""]

    # 2. cross-source tables
    for policy in ("tF1", "t5", "default_0.5"):
        rows = []
        for m in main + supp:
            cells = [name(m) + ("" if m in main else " *")]
            for dataset in ("d1", "d2", "d3"):
                r = metrics[(metrics.model_id == m) & (metrics.threshold_policy == policy)
                            & (metrics.dataset == dataset) & (metrics.split == "test")].iloc[0]
                cells += [f4(r.macro_f1) + ci(r.macro_f1_ci_low, r.macro_f1_ci_high, f4), pct(r.attack_recall), pct(r.fpr)]
            rows.append(cells)
        header = ["Model"] + [f"{d} {k}" for d in ("D1", "D2", "D3") for k in ("Macro F1 [95% CI]", "Recall", "FPR")]
        parts += [f"## 2{'abc'[('tF1', 't5', 'default_0.5').index(policy)]}. Test results at {policy}", "",
                  table(header, rows), "", "\\* supplementary (E5).", ""]

    # 3. D4
    rows = []
    for m in order:
        cells = [name(m)]
        for policy in ("default_0.5", "tF1", "t5"):
            r = notinject[(notinject.model_id == m) & (notinject.threshold_policy == policy) & (notinject.group_by == "overall")]
            if r.empty or not r.iloc[0].n:
                cells.append("no D4 scores")
            else:
                r = r.iloc[0]
                cells.append(f"{int(r.fp)}/{int(r.n)} = {pct(r.fpr)}{ci(r.ci_low, r.ci_high)}")
        rows.append(cells)
    parts += ["## 3. NotInject (D4, 339 benign prompts) false alarms — FP/N, FPR [Wilson 95% CI]", "",
              table(["Model", "@0.5", "@tF1", "@t5"], rows), ""]

    rows = []
    for m in order:
        r = notinject[(notinject.model_id == m) & (notinject.threshold_policy == "tF1") & (notinject.group_by == "trigger_count")]
        if r.empty:
            continue
        rows.append([name(m)] + [f"{int(x.fp)}/{int(x.n)} = {pct(x.fpr)}" for _, x in r.sort_values("group").iterrows()])
    if rows:
        parts += ["### D4 by number of trigger words (at tF1)", "",
                  table(["Model", "1 trigger", "2 triggers", "3 triggers"], rows), ""]

    rows = []
    for m in order:
        r = notinject[(notinject.model_id == m) & (notinject.group_by.isin(["overall", "multilingual"]))]
        if r.empty or not r.n.max():
            continue
        for group in ("all", "Non-Multilingual", "Multilingual"):
            cells = [name(m) if group == "all" else "", "All subsets" if group == "all" else group]
            for policy in ("tF1", "t5"):
                x = r[(r.threshold_policy == policy) & (r.group == group)].iloc[0]
                cells += [str(int(x.n)) if policy == "tF1" else None, str(int(x.fp)), pct(x.fpr) + ci(x.ci_low, x.ci_high)]
            rows.append([c for c in cells if c is not None])
    if rows:
        parts += ["### Report Table 9 layout (per model)", "",
                  table(["Model", "NotInject group", "N", "FP (tF1)", "FPR (tF1) [95% CI]", "FP (t5)", "FPR (t5) [95% CI]"], rows),
                  "", "\"Non-Multilingual\" is the source category, not validated English identification.", ""]

    # 4. D3 slices
    families = sorted(d3_slices.attack_family.unique(), key=lambda f: (f != "benign", f))
    rows = []
    for m in order:
        cells = [name(m)]
        for fam in families:
            r = d3_slices[(d3_slices.model_id == m) & (d3_slices.threshold_policy == "tF1") & (d3_slices.attack_family == fam)].iloc[0]
            cells.append(f"{pct(r.rate)}")
        rows.append(cells)
    parts += ["## 4. D3 by attack family at tF1 (benign column = FPR, others = attack recall)", "",
              table(["Model"] + families, rows), ""]

    warnings = [f"- `{m}`: {w}" for m in order for w in models[m]["warnings"]]
    if warnings:
        parts += ["## Input warnings", "", *warnings, ""]
    path.write_text("\n".join(parts) + "\n", encoding="utf-8", newline="\n")
